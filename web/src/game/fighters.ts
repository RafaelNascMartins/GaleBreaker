export function getEffectiveMoveData(
  fighterId: FighterId,
  moveType: MoveType,
  unlockedSkills: string[]
): MoveFrameData {
  const def = FIGHTERS[fighterId];
  const base = def.moves[moveType];
  let startupReduction = 0;
  let damageMult = 1;
  let gustBonus = 0;
  let chipBonus = 0;
  let meterMult = 1;

  for (const skill of def.skillTree) {
    if (unlockedSkills.includes(skill.id)) {
      if (skill.effect.startupReductionFrames) {
        startupReduction += skill.effect.startupReductionFrames;
      }
      if (skill.effect.damageMultiplier) {
        damageMult *= skill.effect.damageMultiplier;
      }
      if (skill.effect.gustForceBonus) {
        gustBonus += skill.effect.gustForceBonus;
      }
      if (skill.effect.chipDamageBonus) {
        chipBonus += skill.effect.chipDamageBonus;
      }
      if (skill.effect.meterGainMultiplier) {
        meterMult *= skill.effect.meterGainMultiplier;
      }
    }
  }

  return {
    ...base,
    startupFrames: Math.max(3, base.startupFrames - startupReduction),
    damage: Math.round(base.damage * damageMult),
    chipDamage: Math.round(base.chipDamage + chipBonus),
    gustForce: Number((base.gustForce * (1 + gustBonus)).toFixed(1)),
    meterGain: Math.round(base.meterGain * meterMult),
  };
}

export function getEffectiveMaxHp(fighterId: FighterId, unlockedSkills: string[]): number {
  const def = FIGHTERS[fighterId];
  let bonus = 0;
  for (const skill of def.skillTree) {
    if (unlockedSkills.includes(skill.id) && skill.effect.maxHpBonus) {
      bonus += skill.effect.maxHpBonus;
    }
  }
  return def.baseHp + bonus;
}

