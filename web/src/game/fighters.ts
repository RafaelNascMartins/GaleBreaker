export function resolveMirrorPaletteIndex(
  p1Id: FighterId,
  p1Palette: number,
  p2Id: FighterId,
  p2DesiredPalette = 0
): number {
  if (p1Id !== p2Id) return p2DesiredPalette;
  return p1Palette === p2DesiredPalette ? (p1Palette + 1) % 4 : p2DesiredPalette;
}

